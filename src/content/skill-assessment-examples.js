export function skillAssessmentExample(id) {
  const example = examples[id];
  if (!example) return null;
  const [scores, summary] = example;
  const score = Math.round(scores.reduce((sum, value) => sum + value, 0) / scores.length * 10) / 10;
  const tier = score >= 4.5 ? '优秀' : score >= 4 ? '良好' : score >= 3 ? '合格' : score >= 2 ? '待改进' : '需复核';
  return { scores, summary, score, tier, findings: findings[id] };
}
